#pragma once

#include <cstdint>

#ifdef _WIN32
#include <windows.h>
#endif

namespace electrobun {

// Protected by the host's frame mutex. A flight lasts until its low-priority
// paint or fallback timer actually renders, not merely until a posted wakeup
// starts executing.
// Separate wake/paint phases keep an unrelated WM_PAINT from completing a
// queued wakeup; unique flight tokens reject work from retired attachments.
class UIFrameSchedule {
    enum class Phase { idle, wakeQueued, paintPending, rendering };
    bool requested_ = false;
    Phase phase_ = Phase::idle;
    uint64_t flight_ = 0;

public:
    void request() { requested_ = true; }
    bool ready() const { return requested_ && phase_ == Phase::idle; }
    uint64_t activeFlight() const { return flight_; }

    bool queue(uint64_t token) {
        if (!ready() || token == 0) return false;
        requested_ = false;
        flight_ = token;
        phase_ = Phase::wakeQueued;
        return true;
    }

    bool acceptWake(uint64_t token) {
        if (phase_ != Phase::wakeQueued || flight_ != token) return false;
        phase_ = Phase::paintPending;
        return true;
    }

    uint64_t beginPaint() {
        if (phase_ != Phase::paintPending) return 0;
        phase_ = Phase::rendering;
        return flight_;
    }

    uint64_t beginTimer(uint64_t token) {
        if (phase_ != Phase::paintPending || flight_ != token) return 0;
        return beginPaint();
    }

    bool finishPaint(uint64_t token) {
        if (phase_ != Phase::rendering || flight_ != token) return false;
        phase_ = Phase::idle;
        flight_ = 0;
        return true;
    }

    bool cancel(uint64_t token) {
        if (phase_ == Phase::idle || flight_ != token) return false;
        phase_ = Phase::idle;
        flight_ = 0;
        return true;
    }

    // A nested paint cannot render while the outer GPU frame is running. If
    // this consumed the pending paint notification, arrange another flight.
    void deferPaint() {
        request();
        if (phase_ == Phase::paintPending) {
            phase_ = Phase::idle;
            flight_ = 0;
        }
    }
};

#ifdef _WIN32
inline bool requestLowPriorityUIFrame(HWND window, uint64_t flight) {
    // Unlike PostMessage(WM_PAINT), an internal paint is generated by Windows
    // after queued hardware input. Hidden child windows may never receive it,
    // so arm a lower-priority timer for the same flight before requesting paint.
    // Visible views can paint immediately; hiding after this call remains safe.
    const auto timerId = static_cast<UINT_PTR>(flight);
    if (!window || !IsWindow(window) || flight == 0 ||
        static_cast<uint64_t>(timerId) != flight) return false;
    if (!SetTimer(window, timerId, USER_TIMER_MINIMUM, nullptr)) return false;
    if (!RedrawWindow(window, nullptr, nullptr, RDW_INTERNALPAINT | RDW_NOCHILDREN)) {
        KillTimer(window, timerId);
        return false;
    }
    return true;
}
#endif

} // namespace electrobun
