#pragma once

#include <cstdint>

#ifdef _WIN32
#include <windows.h>
#endif

namespace electrobun {

// Protected by the host's frame mutex. A flight lasts until its low-priority
// paint actually renders, not merely until a posted wakeup starts executing.
// Separate wake/paint phases keep an unrelated WM_PAINT from completing a
// queued wakeup; unique flight tokens reject work from retired attachments.
class UIFrameSchedule {
    enum class Phase { idle, wakeQueued, paintPending, rendering };
    bool requested_ = false;
    Phase phase_ = Phase::idle;
    uint64_t flight_ = 0;

public:
    void request() { requested_ = true; }
    bool ready() const { return requested_ && phase_ == Phase::idle; }

    bool queue(uint64_t token) {
        if (!ready() || token == 0) return false;
        requested_ = false;
        flight_ = token;
        phase_ = Phase::wakeQueued;
        return true;
    }

    bool acceptWake(uint64_t token) {
        if (phase_ != Phase::wakeQueued || flight_ != token) return false;
        phase_ = Phase::paintPending;
        return true;
    }

    uint64_t beginPaint() {
        if (phase_ != Phase::paintPending) return 0;
        phase_ = Phase::rendering;
        return flight_;
    }

    bool finishPaint(uint64_t token) {
        if (phase_ != Phase::rendering || flight_ != token) return false;
        phase_ = Phase::idle;
        flight_ = 0;
        return true;
    }

    bool cancel(uint64_t token) {
        if (phase_ == Phase::idle || flight_ != token) return false;
        phase_ = Phase::idle;
        flight_ = 0;
        return true;
    }

    // A nested paint cannot render while the outer GPU frame is running. If
    // this consumed the pending paint notification, arrange another flight.
    void deferPaint() {
        request();
        if (phase_ == Phase::paintPending) {
            phase_ = Phase::idle;
            flight_ = 0;
        }
    }
};

#ifdef _WIN32
inline bool requestLowPriorityUIFrame(HWND window) {
    // Unlike PostMessage(WM_PAINT), an internal paint is generated by Windows
    // after queued hardware input. It also works without an invalid region.
    return window && IsWindow(window) && RedrawWindow(window, nullptr, nullptr,
                        RDW_INTERNALPAINT | RDW_NOCHILDREN) != FALSE;
}
#endif

} // namespace electrobun
